"""Export LPG stations from a pre-filtered OpenStreetMap PBF to GeoJSON.

Input:  lpg.osm.pbf (generated by osmium tags-filter)
Output: data/lpg_deutschland.geojson
"""
import json
from pathlib import Path
import osmium

SOURCE = Path('lpg.osm.pbf')
OUTPUT = Path('data/lpg_deutschland.geojson')


class LPGExporter(osmium.SimpleHandler):
    def __init__(self, output):
        super().__init__()
        self.output = output
        self.first = True
        self.nodes = 0
        self.ways = 0

    def write_station(self, obj, kind, lat, lon):
        if not (-90 <= lat <= 90 and -180 <= lon <= 180):
            return
        tags = obj.tags
        props = {
            'osm_type': kind,
            'osm_id': obj.id,
            'name': tags.get('name', 'Autogas-Tankstelle'),
            'brand': tags.get('brand', ''),
            'operator': tags.get('operator', ''),
            'street': tags.get('addr:street', ''),
            'housenumber': tags.get('addr:housenumber', ''),
            'postcode': tags.get('addr:postcode', ''),
            'city': tags.get('addr:city', ''),
            'opening_hours': tags.get('opening_hours', ''),
            'fuel:lpg': 'yes',
        }
        feature = {
            'type': 'Feature',
            'geometry': {
                'type': 'Point',
                'coordinates': [round(lon, 7), round(lat, 7)],
            },
            'properties': props,
        }
        if not self.first:
            self.output.write(',\n')
        self.first = False
        self.output.write(json.dumps(feature, ensure_ascii=False, separators=(',', ':')))

    def node(self, n):
        if n.tags.get('fuel:lpg') == 'yes' and n.location.valid():
            self.write_station(n, 'node', n.location.lat, n.location.lon)
            self.nodes += 1

    def way(self, w):
        if w.tags.get('fuel:lpg') != 'yes':
            return
        coords = [(p.location.lat, p.location.lon) for p in w.nodes if p.location.valid()]
        if not coords:
            return
        if len(coords) > 1 and coords[0] == coords[-1]:
            coords.pop()
        if not coords:
            return
        lat = sum(point[0] for point in coords) / len(coords)
        lon = sum(point[1] for point in coords) / len(coords)
        self.write_station(w, 'way', lat, lon)
        self.ways += 1


def main():
    if not SOURCE.is_file():
        raise SystemExit(f'Input file not found: {SOURCE}')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    temporary = OUTPUT.with_suffix('.geojson.tmp')
    try:
        with temporary.open('w', encoding='utf-8') as out:
            out.write('{"type":"FeatureCollection","features":[\n')
            exporter = LPGExporter(out)
            exporter.apply_file(str(SOURCE), locations=True, idx='flex_mem')
            out.write('\n]}\n')
        if exporter.nodes + exporter.ways == 0:
            raise RuntimeError('No LPG stations found; refusing to publish an empty dataset')
        temporary.replace(OUTPUT)
    except Exception:
        temporary.unlink(missing_ok=True)
        raise
    print(f'Export complete: {exporter.nodes} nodes, {exporter.ways} ways')
    print(f'Output: {OUTPUT}')


if __name__ == '__main__':
    main()
